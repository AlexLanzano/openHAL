#ifndef OHAL_TYPES_H
#define OHAL_TYPES_H

#include <stdint.h>

/**
 * @file types.h
 * @brief Common typedef aliases for fixed-width integer types.
 */

/** Unsigned 8-bit value. */
typedef uint8_t u8;
/** Signed 8-bit value. */
typedef int8_t s8;
/** Unsigned 16-bit value. */
typedef uint16_t u16;
/** Signed 16-bit value. */
typedef int16_t s16;
/** Unsigned 32-bit value. */
typedef uint32_t u32;
/** Signed 32-bit value. */
typedef int32_t s32;
/** Unsigned 64-bit value. */
typedef uint64_t u64;
/** Signed 64-bit value. */
typedef int64_t s64;


#endif /* OHAL_TYPES_H */
